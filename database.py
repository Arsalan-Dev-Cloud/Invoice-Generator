def save_invoice(
    user_id,
    invoice_number,
    customer_name,
    customer_email,
    invoice_date,
    subtotal,
    gst,
    grand_total,
    product_names,
    quantities,
    prices
):

    connection = get_connection()
    cursor = connection.cursor()

    try:

        # Insert invoice
        cursor.execute("""
            INSERT INTO invoices (
                user_id,
                invoice_number,
                customer_name,
                customer_email,
                invoice_date,
                subtotal,
                gst,
                grand_total
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
            RETURNING id
        """, (
            user_id,
            invoice_number,
            customer_name,
            customer_email,
            invoice_date,
            subtotal,
            gst,
            grand_total
        ))

        invoice_id = cursor.fetchone()["id"]

        # Insert invoice items
        for product_name, quantity, price in zip(
            product_names,
            quantities,
            prices
        ):

            total = float(quantity) * float(price)

            cursor.execute("""
                INSERT INTO invoice_items (
                    invoice_id,
                    product_name,
                    quantity,
                    price,
                    total
                )
                VALUES (%s, %s, %s, %s, %s)
            """, (
                invoice_id,
                product_name,
                quantity,
                price,
                total
            ))

        connection.commit()

        print("Invoice saved to database!")

        return invoice_id

    except Exception:

        connection.rollback()

        raise

    finally:

        cursor.close()
        release_connection(connection)


