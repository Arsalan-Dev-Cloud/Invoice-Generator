def delete_user_account(user_id):

    connection = get_connection()
    cursor = connection.cursor()

    try:

        # Delete invoice items first
        cursor.execute("""
            DELETE FROM invoice_items
            WHERE invoice_id IN (
                SELECT id
                FROM invoices
                WHERE user_id = %s
            )
        """, (user_id,))

        # Delete invoices
        cursor.execute("""
            DELETE FROM invoices
            WHERE user_id = %s
        """, (user_id,))

        # Delete password reset tokens
        cursor.execute("""
            DELETE FROM password_reset_tokens
            WHERE user_id = %s
        """, (user_id,))

        # Delete invoice counter
        cursor.execute("""
            DELETE FROM invoice_counters
            WHERE user_id = %s
        """, (user_id,))

        # Delete activity logs
        cursor.execute("""
            DELETE FROM activity_logs
            WHERE user_id = %s
        """, (user_id,))

        # Finally delete the user
        cursor.execute("""
            DELETE FROM users
            WHERE id = %s
        """, (user_id,))

        connection.commit()

        print("User account deleted successfully!")

    except Exception:

        connection.rollback()

        raise

    finally:

        cursor.close()
        release_connection(connection)


